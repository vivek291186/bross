def build():
    rows = []
    ai, bi = 0, 0
    for d in range(90):
        date = START + datetime.timedelta(days=d)
        f = FEST.get(date)
        event = f[0] if f else ""
        for slot in ("A", "B"):
            spec = None
            if f:
                spec = f[1] if slot == "A" else f[2]
            if spec is None:
                if slot == "A":
                    t, seg, learn = A_POOL[ai % len(A_POOL)]; ai += 1
                    spec = ("Bro Battle", t, seg, learn)
                else:
                    fmt, t, seg, learn = B_POOL[bi % len(B_POOL)]; bi += 1
                    spec = (fmt, t, seg, learn)
            fmt, title, seg, learn = spec
            rows.append({
                "day": d + 1,
                "date": date.isoformat(),
                "weekday": date.strftime("%a"),
                "slot": slot,
                "event": event,
                "format": fmt,
                "title": title,
                "segments": seg,
                "learning": learn,
                "length": "11-13 min" if slot == "A" else "10-12 min",
            })
    return rows, ai, bi

if __name__ == "__main__":
    rows, ai, bi = build()
    titles = [r["title"] for r in rows]
